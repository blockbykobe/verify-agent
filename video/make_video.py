def render_slide(i: int, s: dict, path: Path, total: int) -> None:
    fig = plt.figure(figsize=(19.2, 10.8), dpi=100, facecolor=BG)
    fig.text(0.05, 0.92, s["title"], fontsize=40, color=INK, weight="bold", va="top")
    fig.add_artist(plt.Line2D([0.05, 0.95], [0.83, 0.83], color=ACCENT, linewidth=3))
    if s.get("image"):
        ax = fig.add_axes([0.05, 0.06, 0.9, 0.74])
        ax.imshow(mpimg.imread(IMG / s["image"]))
        ax.axis("off")
    else:
        y = 0.75
        for b in s["bullets"]:
            lines = textwrap.wrap(b, 70) or [""]
            for k, line in enumerate(lines):
                prefix = "•  " if k == 0 and not b.startswith("    ") else "    "
                fig.text(0.07, y, prefix + line.strip(), fontsize=30, color=INK, va="top")
                y -= 0.075
            y -= 0.025
    fig.text(0.95, 0.03, f"{i + 1} / {total}", fontsize=16, color=INK2, ha="right")
    fig.text(0.05, 0.03, "verify-agent · github.com/blockbykobe/verify-agent", fontsize=16, color=INK2)
    fig.savefig(path, facecolor=BG)
    plt.close(fig)


def synth(text: str, voice: str, path: Path) -> float:
    import sys
    subprocess.run([sys.executable, "-m", "piper", "-m", voice, "-f", str(path), "--sentence-silence", "0.35"],
                   input=text.encode(), check=True, capture_output=True)
    with wave.open(str(path)) as w:
        return w.getnframes() / w.getframerate()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    with tempfile.TemporaryDirectory(dir=Path(args.out).resolve().parent) as td:
        td = Path(td)
        parts, total_sec = [], 0.0
        for i, s in enumerate(SLIDES):
            png, wav, mp4 = td / f"s{i:02d}.png", td / f"s{i:02d}.wav", td / f"s{i:02d}.mp4"
            render_slide(i, s, png, len(SLIDES))
            dur = synth(s["say"], args.voice, wav) + 1.0  # секунда тишины после каждого слайда
            total_sec += dur
            subprocess.run([ff, "-y", "-loglevel", "error", "-loop", "1", "-i", str(png), "-i", str(wav),
                            "-af", "apad=pad_dur=1", "-t", f"{dur:.2f}", "-c:v", "libx264", "-tune", "stillimage",
                            "-pix_fmt", "yuv420p", "-r", "25", "-c:a", "aac", "-b:a", "128k", str(mp4)], check=True)
            parts.append(mp4)
            print(f"slide {i + 1}/{len(SLIDES)}: {dur:.1f}s", flush=True)
        lst = td / "list.txt"
        lst.write_text("".join(f"file '{p}'\n" for p in parts))
        subprocess.run([ff, "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", str(lst), "-c", "copy",
                        args.out], check=True)
    print(f"done: {args.out}  ({total_sec / 60:.1f} min)")


if __name__ == "__main__":
    main()
